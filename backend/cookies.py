"""Куки: сессия эксперта и временные данные шага авторизации.

Имена кук и их свойства собраны здесь, чтобы правила безопасности не
разъезжались по обработчикам.
"""

# Кука сессии. Живёт в ней токен, в базе только его HMAC.
КУКА_СЕССИИ = "session"

# Кука шага авторизации: `state` и `code_verifier`. Живёт десять минут, потому
# что ровно столько Яндекс держит код подтверждения.
КУКА_АВТОРИЗАЦИИ = "yandex_auth"
СРОК_КУКИ_АВТОРИЗАЦИИ_СЕКУНД = 600

# `Lax` достаточно: кука нужна только на возврате от Яндекса, то есть на
# переходе верхнего уровня. `Strict` запретил бы её даже там, `None` отдал бы
# её стороннему сайту вместе с запросом.
ПОЛИТИКА_КУКИ = "lax"


def кука_сессии(значение: str, срок_секунд: int) -> dict[str, str]:
    """Свойства куки сессии."""
    return {
        "key": КУКА_СЕССИИ,
        "value": значение,
        "max_age": срок_секунд,
        "httponly": True,
        "samesite": ПОЛИТИКА_КУКИ,
        "path": "/",
    }


def пустая_кука_сессии() -> dict[str, str]:
    """Сброс куки сессии при выходе."""
    return кука_сессии("", 0)


def временная_кука_авторизации(значение: str) -> dict[str, str]:
    return {
        "key": КУКА_АВТОРИЗАЦИИ,
        "value": значение,
        "max_age": СРОК_КУКИ_АВТОРИЗАЦИИ_СЕКУНД,
        "httponly": True,
        "samesite": ПОЛИТИКА_КУКИ,
        "path": "/",
    }