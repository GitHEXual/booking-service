"""Отправка писем через SMTP и их тексты.

Писем два повода. Организатору сообщаем сразу, как только гость записался и
встреча создана. Гостю напоминаем перед началом, потому что до встречи ссылка
ему ещё не нужна.
"""

import smtplib
from email.message import EmailMessage
from email.utils import formataddr

from backend.config import Settings

# Многострочный текст письма. Плоский, без разметки: почтовые клиенты
# показывают по-разному, а письмо должно читаться везде одинаково.
_ШАБЛОН = """Здравствуйте, {имя}!

Встреча «{встреча}» с {эксперт} начинается в {время}.

Подключиться:
{ссылка}

Ссылка ведёт в комнату ожидания Телемоста. Если вы не подключитесь сразу,
никто не увидит, что вы вошли: войдите по ссылке из этого письма.

Служба записи на встречи"""


def текст_письма(
    *, имя: str, встреча: str, эксперт: str, время: str, ссылка: str
) -> str:
    """Собрать текст письма о начале встречи."""
    return _ШАБЛОН.format(
        имя=имя,
        встреча=встреча,
        эксперт=эксперт,
        время=время,
        ссылка=ссылка,
    )


_ШАБЛОН_ОРГАНИЗАТОРУ = """Новая заявка на «{встреча}».

Гость: {гость}
Почта гостя: {почта}
Время: {время}

Встреча в Телемосте создана. Подключиться можно по ссылке:
{ссылка}

Служба записи на встречи"""


def текст_письма_организатору(
    *, встреча: str, гость: str, почта: str, время: str, ссылка: str
) -> str:
    """Текст письма организатору о новой заявке и созданной встрече."""
    return _ШАБЛОН_ОРГАНИЗАТОРУ.format(
        встреча=встреча,
        гость=гость,
        почта=почта,
        время=время,
        ссылка=ссылка,
    )


def тема_письма_о_заявке(встреча: str) -> str:
    """Тема письма организатору: пришла новая заявка."""
    return f"Новая заявка на «{встреча}»"


def тема_письма(встреча: str) -> str:
    """Тема письма гостю: встреча начинается."""
    return f"Встреча «{встреча}» начинается"


def отправить(настройки: Settings, *, кому: str, тема: str, текст: str) -> None:
    """Отправить письмо.

    Ошибку не глотаем: письмо, которое не ушло, должно остаться в очереди и
    ждать следующей попытки, а не считаться отправленным.
    """
    письмо = EmailMessage()
    письмо["Subject"] = тема
    # Имя отправителя отделено от адреса: письмо уходит с ящика сервиса, и в
    # списке писем видно «Сервис записи на встречи», а не адрес организатора.
    письмо["From"] = formataddr((настройки.mail_from_name, настройки.smtp_username))
    письмо["To"] = кому
    письмо.set_content(текст)

    with smtplib.SMTP_SSL(
        настройки.smtp_host, настройки.smtp_port, timeout=30
    ) as сервер:
        сервер.login(настройки.smtp_username, настройки.smtp_password)
        сервер.send_message(письмо)
