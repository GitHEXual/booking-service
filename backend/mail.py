"""Отправка писем через SMTP и их тексты.

Письмо одно: встреча начинается. Оно уходит за несколько минут до начала и
содержит ссылку на встречу в Телемосте.
"""

import smtplib
from email.message import EmailMessage

from backend.config import Settings

# Многострочный текст письма. Плоский, без разметки: почтовые клиенты
# показывают по-разному, а письмо должно читаться везде одинаково.
_ШАБЛОН = """Здравствуйте, {имя}!

Встреча «{встреча}» с {эксперт} начинается в {время}.

Подключиться:
{ссылка}

Ссылка ведёт в комнату ожидания Телемоста. Если вы не подключитесь сразу,
никто не увидит, что вы вошли: войдите по ссылке из этого письма.

Служба записи на встречи"""


def текст_письма(
    *, имя: str, встреча: str, эксперт: str, время: str, ссылка: str
) -> str:
    """Собрать текст письма о начале встречи."""
    return _ШАБЛОН.format(
        имя=имя,
        встреча=встреча,
        эксперт=эксперт,
        время=время,
        ссылка=ссылка,
    )


_ШАБЛОН_ЭКСПЕРТУ = """{встреча} начинается в {время}.

Гостей: {гости}
Подключиться:
{ссылка}

Ссылка придёт гостям отдельно, подтверждать ничего не нужно.

Служба записи на встречи"""


def текст_письма_эксперту(
    *, встреча: str, гости: int, время: str, ссылка: str
) -> str:
    """Собрать текст письма самому эксперту."""
    return _ШАБЛОН_ЭКСПЕРТУ.format(
        встреча=встреча, гости=гости, время=время, ссылка=ссылка
    )


def тема_письма(встреча: str) -> str:
    """Тема письма: встреча начинается."""
    return f"Встреча «{встреча}» начинается"


def отправить(настройки: Settings, *, кому: str, тема: str, текст: str) -> None:
    """Отправить письмо.

    Ошибку не глотаем: письмо, которое не ушло, должно остаться в очереди и
    ждать следующей попытки, а не считаться отправленным.
    """
    письмо = EmailMessage()
    письмо["Subject"] = тема
    письмо["From"] = настройки.smtp_username
    письмо["To"] = кому
    письмо.set_content(текст)

    with smtplib.SMTP_SSL(
        настройки.smtp_host, настройки.smtp_port, timeout=30
    ) as сервер:
        сервер.login(настройки.smtp_username, настройки.smtp_password)
        сервер.send_message(письмо)
