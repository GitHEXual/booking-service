import { useCallback, useEffect, useState } from "react";

import { выйти, кто_я, type Эксперт } from "./api";
import { Вход } from "./components/Вход";
import { Профиль } from "./components/Профиль";

/** Что известно о вошедшем человеке на текущий момент. */
type Состояние =
  | { вид: "проверяем" }
  | { вид: "не_вошёл" }
  | { вид: "вошёл"; эксперт: Эксперт }
  | { вид: "ошибка"; сообщение: string };

export function Приложение() {
  const [состояние, setСостояние] = useState<Состояние>({ вид: "проверяем" });

  // Кто вошёл, спрашиваем один раз при открытии страницы. Отдельный запрос не
  // нужен: сессия живёт в куке и сама приходит с каждым обращением.
  useEffect(() => {
    let отменено = false;

    кто_я().then(
      (эксперт) => {
        if (отменено) return;
        setСостояние(
          эксперт ? { вид: "вошёл", эксперт } : { вид: "не_вошёл" },
        );
      },
      (ошибка: unknown) => {
        if (отменено) return;
        setСостояние({
          вид: "ошибка",
          сообщение:
            ошибка instanceof Error
              ? ошибка.message
              : "Не удалось связаться с сервисом",
        });
      },
    );

    return () => {
      отменено = true;
    };
  }, []);

  const выход_из_панели = useCallback(async () => {
    await выйти();
    setСостояние({ вид: "не_вошёл" });
  }, []);

  if (состояние.вид === "проверяем") {
    return (
      <main className="страница страница--узкая">
        <p className="текст текст--приглушенный">Проверяем вход…</p>
      </main>
    );
  }

  if (состояние.вид === "ошибка") {
    return (
      <main className="страница страница--узкая">
        <section className="карточка">
          <h1 className="заголовок">Не получилось загрузить панель</h1>
          <p className="текст текст--приглушенный">{состояние.сообщение}</p>
          <button className="кнопка" onClick={() => location.reload()}>
            Попробовать снова
          </button>
        </section>
      </main>
    );
  }

  if (состояние.вид === "не_вошёл") {
    return <Вход />;
  }

  return (
    <>
      <Профиль эксперт={состояние.эксперт} />
      <footer className="подвал">
        <button className="кнопка кнопка--тихая" onClick={выход_из_панели}>
          Выйти
        </button>
      </footer>
    </>
  );
}
