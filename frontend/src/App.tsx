import { useEffect, useState } from "react";

import { кто_я, type Эксперт } from "./api";
import { Вход } from "./components/Вход";
import { Панель } from "./components/Панель";
import { СтраницаГостя } from "./components/СтраницаГостя";

/** Что известно о вошедшем человеке на текущий момент. */
type Состояние =
  | { вид: "проверяем" }
  | { вид: "не_вошёл" }
  | { вид: "вошёл"; эксперт: Эксперт }
  | { вид: "ошибка"; сообщение: string };

/**
 * Часть адреса после слэша.
 *
 * Своего маршрутизатора в проекте нет: страниц две, и для такого списка
 * условий хватает. Появление нормального маршрутизатора ничего не сломает:
 * проверка ниже это одна функция.
 */
function путь(): string[] {
  return window.location.pathname.split("/").filter(Boolean);
}

export function Приложение() {
  const [состояние, setСостояние] = useState<Состояние>({ вид: "проверяем" });
  const [части] = useState(путь);

  useEffect(() => {
    let отменено = false;

    кто_я().then(
      (эксперт) => {
        if (отменено) return;
        setСостояние(
          эксперт ? { вид: "вошёл", эксперт } : { вид: "не_вошёл" },
        );
      },
      (ошибка: unknown) => {
        if (отменено) return;
        setСостояние({
          вид: "ошибка",
          сообщение:
            ошибка instanceof Error
              ? ошибка.message
              : "Не удалось связаться с сервисом",
        });
      },
    );

    return () => {
      отменено = true;
    };
  }, []);

  // Публичная ссылка гостя `/u/{логин}/{адрес}` видна без входа, поэтому
  // проверка входа идёт после неё.
  if (части[0] === "u" && части.length === 3) {
    return <СтраницаГостя owner={части[1]} slug={части[2]} />;
  }

  if (состояние.вид === "проверяем") {
    return (
      <main className="узкая">
        <p className="текст текст--приглушенный">Проверяем вход</p>
      </main>
    );
  }

  if (состояние.вид === "ошибка") {
    return (
      <main className="узкая">
        <h1 className="заголовок">Не получилось загрузить панель</h1>
        <p className="текст текст--приглушенный">{состояние.сообщение}</p>
        <button className="кнопка" onClick={() => location.reload()}>
          Попробовать снова
        </button>
      </main>
    );
  }

  if (состояние.вид === "не_вошёл") {
    return <Вход />;
  }

  return <Панель эксперт={состояние.эксперт} />;
}
