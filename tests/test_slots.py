"""Тесты расчёта сетки слотов.

Движок не ходит в базу, поэтому проверяется на обычных объектах. Особое
внимание часовым поясам: тесты должны проходить при любом поясе машины, иначе
на чужом компьютере они начнут падать.
"""

from datetime import UTC, date, datetime, time, timedelta
from zoneinfo import ZoneInfo

from backend.slots import Правило, build_slots, find_slot

КРАСНОЯРСК = ZoneInfo("Asia/Krasnoyarsk")

# Понедельник 5 октября 2026 года.
ПОНЕДЕЛЬНИК = date(2026, 10, 5)


def правило(**замены) -> Правило:
    """Правило по умолчанию: по будням, с 9 до 18, шаг 30 минут."""
    значения = {
        "weekdays": frozenset({1, 2, 3, 4, 5}),
        "start_time": time(9, 0),
        "end_time": time(18, 0),
        "timezone": "Asia/Krasnoyarsk",
        "duration": timedelta(minutes=30),
        "increment": timedelta(minutes=30),
        "min_notice": timedelta(0),
        "horizon": timedelta(days=1),
    }
    return Правило(**значения | замены)


def момент(день: date, час: int, минут: int = 0) -> datetime:
    """Момент в локальном времени эксперта, приведённый к UTC."""
    local = datetime.combine(день, time(час, минут), tzinfo=КРАСНОЯРСК)
    return local.astimezone(UTC)


class TestПустаяСетка:
    def test_в_нерабочий_день_пусто(self):
        # Суббота и воскресенье в правило не входят.
        слоты = build_slots(правило(), now=момент(date(2026, 10, 10), 9))
        assert слоты == []

    def test_до_окна_сетка_ещё_есть(self):
        # Запрос в 7:00, окно открывается в 9:00: слоты этого дня должны
        # появиться, ведь они впереди.
        слоты = build_slots(правило(), now=момент(ПОНЕДЕЛЬНИК, 7))
        assert len(слоты) == 18
        первый = слоты[0].start_at.astimezone(КРАСНОЯРСК).time()
        assert первый == time(9, 0)

    def test_окно_пустое(self):
        # Нечётный шаг при нечётной длительности даёт слоты, но сетка не
        # разъезжается: проверяем, что пустое окно честно не даёт ничего.
        пустое = правило(
            start_time=time(9, 0), end_time=time(9, 10), duration=timedelta(minutes=30)
        )
        assert build_slots(пустое, now=момент(ПОНЕДЕЛЬНИК, 8)) == []


class TestСетка:
    def test_слоты_идут_с_шагом(self):
        слоты = build_slots(правило(), now=момент(ПОНЕДЕЛЬНИК, 8))
        начала = [слот.start_at for слот in слоты]
        assert начала == sorted(начала)
        шаг = начала[1] - начала[0]
        assert шаг == timedelta(minutes=30)

    def test_количество_за_день(self):
        # С 9 до 18 шагом 30 и длительностью 30: 9:00, 9:30, ..., 17:30.
        слоты = build_slots(правило(), now=момент(ПОНЕДЕЛЬНИК, 8))
        assert len(слоты) == 18

    def test_слот_целиком_в_окне(self):
        # Инвариант И4: последний слот не может вылезти за конец окна.
        слоты = build_slots(правило(), now=момент(ПОНЕДЕЛЬНИК, 8))
        последний = слоты[-1]
        конец_окна = datetime.combine(ПОНЕДЕЛЬНИК, time(18, 0), tzinfo=КРАСНОЯРСК)
        assert последний.end_at <= конец_окна.astimezone(UTC)

    def test_длительность_выдержана(self):
        # Инвариант И5: конец равен началу плюс длительность.
        for слот in build_slots(правило(), now=момент(ПОНЕДЕЛЬНИК, 8)):
            assert слот.end_at - слот.start_at == timedelta(minutes=30)

    def test_слоты_в_разные_дни(self):
        слоты = build_slots(
            правило(horizon=timedelta(days=3)), now=момент(ПОНЕДЕЛЬНИК, 8)
        )
        дни = {слот.start_at.astimezone(КРАСНОЯРСК).date() for слот in слоты}
        assert дни == {ПОНЕДЕЛЬНИК, date(2026, 10, 6), date(2026, 10, 7)}

    def test_окно_короче_длительности_даёт_пусто(self):
        # Слот длиной в два часа не помещается в окно в один час.
        узкое = правило(start_time=time(9, 0), end_time=time(10, 0), duration=timedelta(hours=2))
        assert build_slots(узкое, now=момент(ПОНЕДЕЛЬНИК, 8)) == []


class TestОграничения:
    def test_учитывается_минимальное_время_предупреждения(self):
        # Инвариант И7: за час до встречи записаться уже нельзя.
        правило_позднее = правило(min_notice=timedelta(hours=1))
        слоты = build_slots(правило_позднее, now=момент(ПОНЕДЕЛЬНИК, 9))
        # Первым идёт слот в 10:00, а не 9:00.
        первый_локально = слоты[0].start_at.astimezone(КРАСНОЯРСК).time()
        assert первый_локально >= time(10, 0)

    def test_горизонт_ограничивает_сетку(self):
        слоты = build_slots(правило(horizon=timedelta(hours=6)), now=момент(ПОНЕДЕЛЬНИК, 9))
        последний = слоты[-1].start_at.astimezone(КРАСНОЯРСК)
        assert последний.date() == ПОНЕДЕЛЬНИК
        assert последний.time() <= time(15, 0)

    def test_прошедшие_слоты_не_показываются(self):
        # Момент запроса попадает внутрь окна: слот в 9:00 уже не подходит,
        # если момент задан как 9:15.
        слоты = build_slots(правило(), now=момент(ПОНЕДЕЛЬНИК, 9, 15))
        первый = слоты[0].start_at.astimezone(КРАСНОЯРСК).time()
        assert первый >= time(9, 30)


class TestЗанятость:
    def test_занятый_слот_остаётся_в_сетке(self):
        # Гость должен видеть занятое время, иначе не поймёт, куда писать.
        занятый = момент(ПОНЕДЕЛЬНИК, 10)
        слоты = build_slots(
            правило(taken=frozenset({занятый})), now=момент(ПОНЕДЕЛЬНИК, 8)
        )
        найденный = [слот for слот in слоты if слот.start_at == занятый]
        assert найденный, "занятый слот должен быть в сетке"
        assert найденный[0].is_taken is True
        assert найденный[0].can_request is False

    def test_свободный_слот_доступен(self):
        слоты = build_slots(правило(), now=момент(ПОНЕДЕЛЬНИК, 8))
        первый = слоты[0]
        assert первый.is_taken is False
        assert первый.can_request is True

    def test_закрытый_слот_не_принимает_заявки(self):
        # Состав закреплён: время в сетке есть, но записаться на него нельзя.
        закрытый = момент(ПОНЕДЕЛЬНИК, 10)
        слоты = build_slots(
            правило(closed=frozenset({закрытый})), now=момент(ПОНЕДЕЛЬНИК, 8)
        )
        нужный = next(слот for слот in слоты if слот.start_at == закрытый)
        assert нужный.is_taken is True
        assert нужный.can_request is False

    def test_один_гость_не_влияет_на_другие_слоты(self):
        # Правило «один слот это один гость» не превращает всю сетку в занятую.
        занятый = момент(ПОНЕДЕЛЬНИК, 10)
        слоты = build_slots(
            правило(taken=frozenset({занятый})), now=момент(ПОНЕДЕЛЬНИК, 8)
        )
        assert sum(1 for слот in слоты if слот.can_request) == len(слоты) - 1


class TestПоискСлота:
    def test_находит_слот_из_сетки(self):
        момент_начала = момент(ПОНЕДЕЛЬНИК, 8)
        найденный = find_slot(
            правило(), момент(ПОНЕДЕЛЬНИК, 10), now=момент_начала
        )
        assert найденный is not None
        assert найденный.start_at == момент(ПОНЕДЕЛЬНИК, 10)

    def test_время_вне_сетки_не_находится(self):
        # `10:07` в расписании нет, и заявку на него принять нельзя.
        найденный = find_slot(
            правило(),
            момент(ПОНЕДЕЛЬНИК, 10, 7),
            now=момент(ПОНЕДЕЛЬНИК, 8),
        )
        assert найденный is None

    def test_время_вне_окна_не_находится(self):
        найденный = find_slot(
            правило(), момент(ПОНЕДЕЛЬНИК, 20), now=момент(ПОНЕДЕЛЬНИК, 8)
        )
        assert найденный is None

    def test_слот_за_пределами_минимального_времени_не_находится(self):
        правило_позднее = правило(min_notice=timedelta(hours=3))
        найденный = find_slot(
            правило_позднее, момент(ПОНЕДЕЛЬНИК, 10), now=момент(ПОНЕДЕЛЬНИК, 9)
        )
        assert найденный is None


class TestЧасовыеПояса:
    def test_слот_начинается_в_окне_эксперта(self):
        # Ключевая проверка перевода: сетка строится в локальном времени
        # эксперта, а отдаётся в UTC. Менять пояс машины нельзя, поэтому
        # сравниваем в поясе самого эксперта.
        слоты = build_slots(правило(), now=момент(ПОНЕДЕЛЬНИК, 8))
        первый = слоты[0].start_at.astimezone(КРАСНОЯРСК)
        assert первый.date() == ПОНЕДЕЛЬНИК
        assert первый.time() == time(9, 0)

    def test_другой_пояс_даёт_другой_utc(self):
        # Одна и та же сетка в разных поясах это разные моменты в UTC.
        под_красноярском = build_slots(правило(), now=момент(ПОНЕДЕЛЬНИК, 8))
        под_москвой = build_slots(
            правило(timezone="Europe/Moscow"), now=момент(ПОНЕДЕЛЬНИК, 8)
        )
        assert под_красноярском[0].start_at != под_москвой[0].start_at
        # Красноярск это UTC+7, Москва UTC+3, поэтому девять утра в Красноярске
        # наступает на четыре часа раньше девяти утра в Москве.
        assert (
            под_красноярском[0].start_at - под_москвой[0].start_at
        ) == timedelta(hours=-4)

    def test_лето_и_зима_различаются(self):
        # Январь и июль в одном поясе отстоят друг от друга на шесть часов
        # из-за перехода на летнее время.
        зимой = build_slots(правило(), now=момент(date(2026, 1, 5), 8))
        летом = build_slots(правило(), now=момент(date(2026, 7, 6), 8))
        assert зимой[0].start_at.astimezone(КРАСНОЯРСК).time() == time(9, 0)
        assert летом[0].start_at.astimezone(КРАСНОЯРСК).time() == time(9, 0)
        assert зимой[0].start_at != летом[0].start_at
